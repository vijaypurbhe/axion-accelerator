const defaultRules = (productId: string, attributes: readonly DataProductAttribute[]): QualityRule[] => {
  const pk = attributes.find((attribute) => attribute.primaryKey);
  const required = attributes.filter((attribute) => attribute.required);
  const rules: QualityRule[] = [];
  if (pk) {
    rules.push({
      id: `${productId}-qr-unique`,
      name: `${pk.businessName} uniqueness`,
      dimension: "uniqueness",
      description: `Every record must carry a distinct ${pk.businessName}.`,
      attributeId: pk.id,
      expression: `COUNT(DISTINCT ${pk.technicalName}) = COUNT(${pk.technicalName})`,
      threshold: 100,
      severity: "critical",
      owner: "data-steward",
      remediation: "Route duplicates to the stewardship queue for merge or reject.",
      cadence: "daily",
      status: "active",
    });
  }
  if (required.length) {
    rules.push({
      id: `${productId}-qr-complete`,
      name: "Mandatory attribute completeness",
      dimension: "completeness",
      description: `Mandatory attributes (${required.slice(0, 4).map((attribute) => attribute.businessName).join(", ")}${required.length > 4 ? "…" : ""}) must be populated.`,
      expression: required.map((attribute) => `${attribute.technicalName} IS NOT NULL`).join(" AND "),
      threshold: 98,
      severity: "high",
      owner: "data-steward",
      remediation: "Raise a source remediation ticket and backfill from the system of record.",
      cadence: "daily",
      status: "active",
    });
  }
  rules.push({
    id: `${productId}-qr-fresh`,
    name: "Ingestion timeliness",
    dimension: "timeliness",
    description: "Records must land within the agreed refresh window.",
    expression: "MAX(ingested_at) >= NOW() - INTERVAL '24 hours'",
    threshold: 99,
    severity: "medium",
    owner: "data-engineer",
    remediation: "Alert the ingestion on-call and re-run the failed batch.",
    cadence: "hourly",
    status: "active",
  });
  return rules;
};

const buildProduct = (spec: ProductSpec): DataProduct => {
  const attributes = spec.attributes;
  const identifiers: DataProductIdentifier[] = (spec.identifiers ?? []).map((identifier, index) => ({
    ...identifier,
    id: `${spec.id}-id-${index + 1}`,
  }));
  const relationships: DataProductRelationship[] = (spec.relationships ?? []).map((relationship, index) => ({
    ...relationship,
    id: `${spec.id}-rel-${index + 1}`,
  }));
  const extraRules: QualityRule[] = (spec.qualityRules ?? []).map((rule, index) => ({
    id: `${spec.id}-qr-x${index + 1}`,
    name: rule.name ?? "Custom rule",
    dimension: rule.dimension ?? "validity",
    description: rule.description ?? "",
    attributeId: rule.attributeId,
    expression: rule.expression ?? "",
    threshold: rule.threshold ?? 95,
    severity: rule.severity ?? "medium",
    owner: rule.owner ?? "data-steward",
    remediation: rule.remediation ?? "Route to the data stewardship queue.",
    cadence: rule.cadence ?? "daily",
    status: rule.status ?? "active",
  }));

  return {
    id: spec.id,
    name: spec.name,
    description: spec.description,
    businessPurpose: spec.businessPurpose,
    category: spec.category,
    domain: spec.domain,
    industry:
      spec.industry ??
      (spec.category === "bfsi"
        ? "BFSI"
        : spec.category === "mfg"
          ? "MFG"
          : spec.category === "auto"
            ? "AUTO"
            : "cross-industry"),
    businessOwnerRole: spec.businessOwnerRole ?? "data-steward",
    technicalOwnerRole: spec.technicalOwnerRole ?? "data360-architect",
    isTemplate: true,
    state: "published",
    version: "1.0.0",
    reuseCount: 0,
    attributes,
    identifiers,
    relationships,
    qualityRules: [...defaultRules(spec.id, attributes), ...extraRules],
    controls: {
      sensitivity: spec.controls?.sensitivity ?? "confidential",
      classifications: spec.controls?.classifications ?? ["Business critical"],
      regulatory: spec.controls?.regulatory ?? ["GDPR", "CCPA"],
      retention: spec.controls?.retention ?? "7 years from last activity, then anonymise.",
      consentImplications:
        spec.controls?.consentImplications ??
        "Downstream activation requires a valid marketing or servicing lawful basis.",
      encryptionRequired: spec.controls?.encryptionRequired ?? true,
      maskingRequired: spec.controls?.maskingRequired ?? false,
      residency: spec.controls?.residency ?? "In-region storage; no cross-border replication without approval.",
    },
    sampleSourceMappings: spec.sampleSourceMappings ?? [],
    salesforceAlignment: spec.salesforceAlignment,
    conceptualDlo: spec.conceptualDlo,
    standardizedDmo: spec.standardizedDmo,
    applicableUseCases: spec.applicableUseCases ?? [],
    stages: spec.stages ?? ["design", "configure"],
    versions: [
      {
        id: `${spec.id}-v1`,
        version: "1.0.0",
        state: "published",
        createdAt: SEED_DATE,
        createdBy: "Axion accelerator library",
        summary: "Initial published template.",
        changes: [{ field: "product", change: "added", after: spec.name }],
      },
    ],
    approvals: [],
    ...audit,
  };
};


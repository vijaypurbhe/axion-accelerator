const slug = (value: string) =>
  value
    .replace(/([a-z0-9])([A-Z])/g, "$1-$2")
    .replace(/[^a-zA-Z0-9]+/g, "-")
    .toLowerCase()
    .replace(/^-|-$/g, "");

/**
 * Compact attribute DSL: "technicalName|Business Name|type|flags|description"
 * flags: R = required, PK = primary key, AK = alternate key, S:<sensitivity>
 */
const A = (spec: string, extra: Partial<DataProductAttribute> = {}): DataProductAttribute => {
  const [technicalName, businessName, dataType, flags = "", description = ""] = spec.split("|");
  const tokens = flags.split(",").map((token) => token.trim()).filter(Boolean);
  const sensitivityToken = tokens.find((token) => token.startsWith("S:"));
  return {
    id: slug(technicalName),
    technicalName,
    businessName,
    dataType: dataType as DataType,
    description,
    required: tokens.includes("R") || tokens.includes("PK"),
    primaryKey: tokens.includes("PK") || undefined,
    alternateKey: tokens.includes("AK") || undefined,
    sensitivity: (sensitivityToken ? sensitivityToken.slice(2) : "internal") as Sensitivity,
    businessDefinition: extra.businessDefinition ?? description,
    ...extra,
  };
};


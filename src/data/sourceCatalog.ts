const F = (spec: string): SourceField => {
  const [name, dataType, flags = "", description = "", sampleValue] = spec.split("|");
  const tokens = flags.split(",").map((token) => token.trim());
  const sensitivityToken = tokens.find((token) => token.startsWith("S:"));
  return {
    id: name.toLowerCase(),
    name,
    dataType: dataType as DataType,
    nullable: !tokens.includes("R"),
    description,
    sampleValue,
    sensitivity: (sensitivityToken ? sensitivityToken.slice(2) : "internal") as SourceField["sensitivity"],
  };
};

